// qr-code-live-search.js
// Live client-side search for QR Code GridView
// Filters table rows based on the input value (case-insensitive)

(function() {
    // Debounce helper to limit frequent calls
    function debounce(func, wait) {
        let timeout;
        return function() {
            const context = this, args = arguments;
            clearTimeout(timeout);
            timeout = setTimeout(() => func.apply(context, args), wait);
        };
    }

    // Main filter function
    function filterRows() {
        const input = document.getElementById('qr-search-input');
        if (!input) return;
        const filter = input.value.trim().toLowerCase();
        // Find the GridView table generated by Yii2 (usually has class 'grid-view')
        const grid = document.querySelector('.grid-view table');
        if (!grid) return;
        const tbody = grid.tBodies[0];
        if (!tbody) return;
        const rows = tbody.getElementsByTagName('tr');
        for (let i = 0; i < rows.length; i++) {
            const rowText = rows[i].textContent.toLowerCase();
            if (filter === '' || rowText.indexOf(filter) !== -1) {
                rows[i].style.display = '';
            } else {
                rows[i].style.display = 'none';
            }
        }
    }

    // Attach event listener with debounce (300ms)
    document.addEventListener('DOMContentLoaded', function() {
        const input = document.getElementById('qr-search-input');
        if (!input) return;
        input.addEventListener('input', debounce(filterRows, 300));
    });
})();
